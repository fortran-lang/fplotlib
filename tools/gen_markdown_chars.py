"""Generate Unicode punctuation ranges for CommonMark delimiter flanking."""
from pathlib import Path
import unicodedata

root = Path(__file__).resolve().parent.parent
ranges = []
for cp in range(128, 0x110000):
    if not unicodedata.category(chr(cp)).startswith("P"):
        continue
    if ranges and cp == ranges[-1][1] + 1:
        ranges[-1][1] = cp
    else:
        ranges.append([cp, cp])

lines = [
    f"! Generated by tools/gen_markdown_chars.py, Unicode {unicodedata.unidata_version}.",
    "module fplotlib_markdown_chars",
    "    implicit none",
    "    private",
    "    public :: markdown_punctuation",
]
for index, name in enumerate(("FIRST", "LAST")):
    lines.append(f"    integer, parameter :: {name}({len(ranges)}) = [ &")
    values = [str(pair[index]) for pair in ranges]
    for i in range(0, len(values), 10):
        lines.append("        " + ", ".join(values[i:i + 10]) +
                     (", &" if i + 10 < len(values) else "]"))
lines += [
    "contains",
    "    pure logical function markdown_punctuation(cp) result(punct)",
    "        integer, intent(in) :: cp",
    "        integer :: lo, hi, mid",
    "        punct = (cp >= 33 .and. cp <= 47) .or. (cp >= 58 .and. cp <= 64) .or. &",
    "                (cp >= 91 .and. cp <= 96) .or. (cp >= 123 .and. cp <= 126)",
    "        if (cp < 128) return",
    "        lo = 1",
    "        hi = size(FIRST)",
    "        do while (lo <= hi)",
    "            mid = (lo + hi)/2",
    "            if (cp < FIRST(mid)) then",
    "                hi = mid - 1",
    "            else if (cp > LAST(mid)) then",
    "                lo = mid + 1",
    "            else",
    "                punct = .true.",
    "                return",
    "            end if",
    "        end do",
    "    end function markdown_punctuation",
    "end module fplotlib_markdown_chars",
]
(root / "src/fplotlib_markdown_chars.f90").write_text("\n".join(lines) + "\n")
